"""Generate crates/sts-core/src/cards/data.rs from the decompiled card classes.

Extracts the constructor numbers only (cost, type, rarity, target, base damage/block/magic,
flags, tags) plus the English name. Card behaviour is hand-written in Rust.

Usage: python3 -I gen_cards.py <reference dir> <output .rs> <library order file>
  (tools/data/card_library_hash_order.txt)
"""
import json
import re
import sys
from pathlib import Path

ref = Path(sys.argv[1])
out = Path(sys.argv[2])
src = ref / "src/com/megacrit/cardcrawl/cards"
names = json.loads((ref / "assets/localization/eng/cards.json").read_text())

# Hash-map order of the whole card library (see tools/golden/HashMapOrder.java).
library_order = [l for l in Path(sys.argv[3]).read_text().splitlines() if l]

# Directories to include. The order fixes CardId's numbering, which the network's card vocabulary
# uses: new groups go at the end.
groups = ["red", "status", "colorless", "curses", "green", "blue", "purple", "tempCards", "optionCards"]

# Classes no game creates: in no card library and made by nothing (tools/extract/port_checklist.py
# lists them as n/a).
UNUSED = {"Impulse", "Discipline", "Unraveling"}

# The basic Strike and Defend classes per color (Strike_Red -> StrikeR, ...).
SUFFIX = {"_Red": "R", "_Green": "G", "_Blue": "B", "_Purple": "P", "_Watcher": "P"}


def variant(stem):
    if stem == "VoidCard":
        return "Void"
    for s, v in SUFFIX.items():
        stem = stem.replace(s, v)
    return stem.replace("Card", "")


rows = []
for folder in groups:
    for p in sorted((src / folder).glob("*.java")):
        text = p.read_text()
        cid = re.search(r'public static final String ID = "([^"]+)";', text).group(1)
        if cid in UNUSED:
            continue
        sup = re.search(r"super\(\s*(.*?)\);", text, re.S).group(1)
        args = [a.strip() for a in re.split(r",\s*(?![^()]*\))", sup)]
        # super(id, name, img, cost, description, type, color, rarity, target)
        cost = int(args[3])
        ctype = args[5].split(".")[-1]
        color = args[6].split(".")[-1]
        rarity = args[7].split(".")[-1]
        target = args[8].split(".")[-1]

        def num(field):
            m = re.search(r"this\." + field + r" = (-?\d+);", text)
            return int(m.group(1)) if m else 0

        def flag(field):
            return bool(re.search(r"this\." + field + r" = true;", text.split("public void upgrade")[0]))

        tags = re.findall(r"CardTags\.(\w+)\)", text)
        rows.append(
            dict(
                variant=variant(p.stem),
                color=color,
                id=cid,
                name=names[cid]["NAME"],
                cost=cost,
                ctype=ctype,
                rarity=rarity,
                target=target,
                damage=num("baseDamage"),
                block=num("baseBlock"),
                magic=num("baseMagicNumber") or num("magicNumber"),
                exhaust=flag("exhaust"),
                ethereal=flag("isEthereal"),
                innate=flag("isInnate"),
                self_retain=flag("selfRetain"),
                multi=flag("isMultiDamage"),
                strike="STRIKE" in tags,
                healing="HEALING" in tags,
                starter_strike="STARTER_STRIKE" in tags,
                starter_defend="STARTER_DEFEND" in tags,
            )
        )

camel = lambda s: "".join(w.capitalize() for w in s.lower().split("_"))
lines = [
    "// @generated by tools/extract/gen_cards.py from the decompiled game. Do not edit by hand.",
    "use super::{CardColor, CardData, CardRarity, CardTarget, CardType};",
    "",
    "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, serde::Serialize, serde::Deserialize)]",
    "pub enum CardId {",
]
for r in rows:
    lines.append(f"    {r['variant']},")
lines += ["}", "", f"pub const ALL_CARDS: [CardId; {len(rows)}] = ["]
for r in rows:
    lines.append(f"    CardId::{r['variant']},")
lines += ["];", "", f"pub const CARD_DATA: [CardData; {len(rows)}] = ["]
for r in rows:
    lines.append(
        "    CardData {{ id: CardId::{variant}, java_id: {jid}, name: {jname}, cost: {cost}, "
        "card_type: CardType::{t}, color: CardColor::{co}, rarity: CardRarity::{ra}, target: CardTarget::{ta}, "
        "damage: {damage}, block: {block}, magic: {magic}, exhaust: {exhaust}, ethereal: {ethereal}, "
        "innate: {innate}, self_retain: {self_retain}, multi_damage: {multi}, strike: {strike}, healing: {healing}, "
        "starter_strike: {starter_strike}, starter_defend: {starter_defend} }},".format(
            jid=json.dumps(r["id"]), jname=json.dumps(r["name"]), t=camel(r["ctype"]), co=camel(r["color"]), ra=camel(r["rarity"]), ta={"SELF": "SelfTarget"}.get(r["target"], camel(r["target"])), **{k: (str(v).lower() if isinstance(v, bool) else v) for k, v in r.items()}
        )
    )
lines += ["];", ""]

# Each character's card pool in CardLibrary HashMap iteration order (non-basic cards).
by_id = {r["id"]: r for r in rows}
for color, method in [("RED", "addRedCards"), ("GREEN", "addGreenCards"), ("BLUE", "addBlueCards"), ("PURPLE", "addPurpleCards")]:
    pool = [by_id[i] for i in library_order if i in by_id and by_id[i]["color"] == color and by_id[i]["rarity"] != "BASIC"]
    lines.append(f"/// {color.title()} cards in `CardLibrary.cards` HashMap iteration order (what `{method}` yields).")
    lines.append(f"pub const {color}_LIBRARY_ORDER: [CardId; {len(pool)}] = [")
    for r in pool:
        lines.append(f"    CardId::{r['variant']},")
    lines += ["];", ""]
for color, const, extra in [("COLORLESS", "COLORLESS_LIBRARY_ORDER", lambda r: r["rarity"] not in ("BASIC", "SPECIAL") and r["ctype"] != "STATUS"),
                            ("CURSE", "CURSE_LIBRARY_ORDER", lambda r: r["ctype"] == "CURSE" and r["id"] not in ("Necronomicurse", "AscendersBane", "CurseOfTheBell", "Pride"))]:
    pool = [by_id[i] for i in library_order if i in by_id and by_id[i]["color"] == color and extra(by_id[i])]
    lines.append(f"/// `{const}`: the card pool built from `CardLibrary.cards` iteration order.")
    lines.append(f"pub const {const}: [CardId; {len(pool)}] = [")
    for r in pool:
        lines.append(f"    CardId::{r['variant']},")
    lines += ["];", ""]
out.write_text("\n".join(lines))
print(f"wrote {len(rows)} cards")
