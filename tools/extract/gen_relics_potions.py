"""Generate relic and potion data tables from the decompiled game.

Writes:
  crates/sts-core/src/relics/data.rs   RelicId, tiers, names, owning class, and the
                                       RelicLibrary HashMap iteration orders
  crates/sts-core/src/potions/data.rs  PotionId, rarity, potency, and PotionHelper's list order

Usage: python3 -I gen_relics_potions.py <reference dir> <repo dir> <relic key orders json>
The orders json maps "shared", "red", "green", "blue" and "purple" to the keys in HashMap
iteration order, computed on the game's JRE (see tools/golden/HashMapOrder.java).
"""
import json
import re
import sys
from pathlib import Path

ref = Path(sys.argv[1])
repo = Path(sys.argv[2])
orders = json.loads(Path(sys.argv[3]).read_text()) if len(sys.argv) > 3 else None
src = ref / "src/com/megacrit/cardcrawl"
relic_names = json.loads((ref / "assets/localization/eng/relics.json").read_text())
potion_names = json.loads((ref / "assets/localization/eng/potions.json").read_text())

camel = lambda s: "".join(w.capitalize() for w in s.lower().split("_"))

# ---- Relics ----
lib = (src / "helpers/RelicLibrary.java").read_text()
init = re.search(r"public static void initialize\(\) \{(.*?)\n   \}", lib, re.S).group(1)
relics = []
for fn, cls in re.findall(r"(add\w*)\(new (\w+)\(", init):
    text = (src / f"relics/{cls}.java").read_text()
    rid = re.search(r'public static final String ID = "([^"]+)";', text).group(1)
    tier = re.search(r"RelicTier\.(\w+)", text).group(1)
    owner = {"add": "Shared", "addRed": "Red", "addGreen": "Green", "addBlue": "Blue", "addPurple": "Purple"}[fn]
    name = relic_names.get(rid, {}).get("NAME", rid)
    relics.append(dict(variant=cls, id=rid, tier=camel(tier), owner=owner, name=name, fn=fn))

# Relics created on demand rather than registered in the library.
for cls in ["Circlet", "RedCirclet"]:
    text = (src / f"relics/{cls}.java").read_text()
    rid = re.search(r'public static final String ID = "([^"]+)";', text).group(1)
    tier = re.search(r"RelicTier\.(\w+)", text).group(1)
    relics.append(dict(variant=cls, id=rid, tier=camel(tier), owner="Shared", name=relic_names.get(rid, {}).get("NAME", rid), fn="extra"))

if orders is None:
    # First pass: print insertion order per map for HashMapOrder.java.
    out = {key: [r["id"] for r in relics if r["fn"] == fn]
           for key, fn in [("shared", "add"), ("red", "addRed"), ("green", "addGreen"), ("blue", "addBlue"), ("purple", "addPurple")]}
    print(json.dumps(out))
    sys.exit(0)

by_id = {r["id"]: r for r in relics}
lines = [
    "// @generated by tools/extract/gen_relics_potions.py from the decompiled game. Do not edit by hand.",
    "use super::{RelicClass, RelicData, RelicTier};",
    "",
    "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, serde::Serialize, serde::Deserialize)]",
    "pub enum RelicId {",
]
lines += [f"    {r['variant']}," for r in relics]
lines += ["}", "", f"pub const RELIC_DATA: [RelicData; {len(relics)}] = ["]
for r in relics:
    lines.append(
        f"    RelicData {{ id: RelicId::{r['variant']}, java_id: {json.dumps(r['id'])}, name: {json.dumps(r['name'])}, "
        f"tier: RelicTier::{r['tier']}, class: RelicClass::{r['owner']} }},"
    )
lines += ["];", ""]
for key, const in [("shared", "SHARED_LIBRARY_ORDER"), ("red", "RED_LIBRARY_ORDER"), ("green", "GREEN_LIBRARY_ORDER"),
                   ("blue", "BLUE_LIBRARY_ORDER"), ("purple", "PURPLE_LIBRARY_ORDER")]:
    ids = orders[key]
    lines.append(f"/// `RelicLibrary` {key} relics in HashMap iteration order.")
    lines.append(f"pub const {const}: [RelicId; {len(ids)}] = [")
    lines += [f"    RelicId::{by_id[i]['variant']}," for i in ids]
    lines += ["];", ""]
(repo / "crates/sts-core/src/relics/data.rs").write_text("\n".join(lines))

# ---- Potions ----
helper = (src / "helpers/PotionHelper.java").read_text()
get_potions = re.search(r"public static ArrayList<String> getPotions\(.*?\n   \}", helper, re.S).group(0)
shared_part = get_potions.split("retVal.add(\"Ambrosia\");\n      }")[1]
shared_order = re.findall(r'retVal\.add\("([^"]+)"\)', shared_part)
class_orders = {}
for case, name in [("IRONCLAD", "IRONCLAD"), ("THE_SILENT", "SILENT"), ("DEFECT", "DEFECT"), ("WATCHER", "WATCHER")]:
    block = re.search(r"case " + case + r":(.*?)(?:break;|\n         \})", get_potions, re.S).group(1)
    class_orders[name] = re.findall(r'retVal\.add\("([^"]+)"\)', block) + shared_order
# The PotionId enum keeps the Ironclad pool's order first (the network's potion ids).
order = class_orders["IRONCLAD"]
# potion id -> class via getPotion's switch.
switch = dict(re.findall(r'case "([^"]+)":\s*return new (\w+)\(\);', helper))
potions = []
for pid in order + [k for k in switch if k not in order]:
    cls = switch[pid]
    p = next((src / "potions").glob(f"{cls}.java"), None)
    text = p.read_text()
    rarity = re.search(r"PotionRarity\.(\w+)", text).group(1)
    m = re.search(r"getPotency\(int ascensionLevel\) \{\s*return (\d+);", text)
    potency = int(m.group(1)) if m else 0
    target = "Enemy" if "this.targetRequired = true;" in text else "None"
    thrown = "this.isThrown = true;" in text
    name = potion_names.get(pid, {}).get("NAME", pid)
    potions.append(dict(variant=cls, id=pid, rarity=camel(rarity), potency=potency, name=name, in_pool=pid in order, target=target, thrown=thrown))
lines = [
    "// @generated by tools/extract/gen_relics_potions.py from the decompiled game. Do not edit by hand.",
    "use super::{PotionData, PotionRarity};",
    "",
    "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, serde::Serialize, serde::Deserialize)]",
    "pub enum PotionId {",
]
lines += [f"    {p['variant']}," for p in potions]
lines += ["}", "", f"pub const POTION_DATA: [PotionData; {len(potions)}] = ["]
for p in potions:
    lines.append(
        f"    PotionData {{ id: PotionId::{p['variant']}, java_id: {json.dumps(p['id'])}, name: {json.dumps(p['name'])}, "
        f"rarity: PotionRarity::{p['rarity']}, potency: {p['potency']}, needs_target: {str(p['target'] == 'Enemy').lower()} }},"
    )
lines += ["];", ""]
for name, pool in class_orders.items():
    lines += [f"/// `PotionHelper.getPotions({name}, false)` order (the pool `getRandomPotion` indexes).",
              f"pub const {name}_POTION_POOL: [PotionId; {len(pool)}] = ["]
    lines += [f"    PotionId::{switch[i]}," for i in pool]
    lines += ["];", ""]
(repo / "crates/sts-core/src/potions").mkdir(exist_ok=True)
(repo / "crates/sts-core/src/potions/data.rs").write_text("\n".join(lines))
print(f"{len(relics)} relics, {len(potions)} potions ({len(order)} in the Ironclad pool)")
